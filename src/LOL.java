public class LOL{
    public static void main(String[] args){

        int Weeks = 3;
        int days = 7;

        for (int i = 1; 1 <= Weeks; ++i){
            System.out.println("Week: " + 1);

            for (int j = 1; j <= days; ++j) {
                System.out.println(" Day: " + j);
            }
        }
    }
}
